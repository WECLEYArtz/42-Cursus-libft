#include "libft.h"

char	*ft_strjoin(char const *s1, char const *s2)
{
	size_t	s1_len;
	size_t	s2_len;
	char	*mem;

	if (!s1 && !s2)
		return (NULL);
	if (!s1)
		return (ft_strdup(s2));
	if (!s2)
		return (ft_strdup(s1));

	s1_len = ft_strlen(s1);
	s2_len = ft_strlen(s2);
	mem = malloc((s1_len + s2_len) + 1);
	if (!mem)
		return (NULL);
	ft_strlcpy(mem, s1, s1_len + 1);
	ft_strlcpy(mem + s1_len, s2, s2_len + 1);
	return (mem);
}
